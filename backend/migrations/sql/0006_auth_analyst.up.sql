-- scouting_template 은 버전 컬럼명이 템플릿 버전과 겹쳐 row_version 을 쓰므로 별도 트리거 함수
CREATE FUNCTION util.analyst_template_before_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.workspace_id IS DISTINCT FROM OLD.workspace_id THEN
        RAISE EXCEPTION '워크스페이스는 변경할 수 없습니다 (table=%, id=%)', TG_TABLE_NAME, OLD.id;
