END $$;

-- ---------------------------------------------------------------------
-- 트리거 부착
-- ---------------------------------------------------------------------
DO $$
DECLARE
    t text;
BEGIN
    -- 수정 메타데이터 트리거 (tag_assignment 는 삽입/삭제만 하므로 제외)
    FOREACH t IN ARRAY ARRAY['scouting_report', 'injury_note', 'tag', 'custom_metric', 'custom_field',
                             'manual_upload', 'manual_stat', 'saved_view'] LOOP
        EXECUTE 'CREATE TRIGGER trg_before_update BEFORE UPDATE ON analyst.' || quote_ident(t)
             || ' FOR EACH ROW EXECUTE FUNCTION util.analyst_before_update()';
    END LOOP;
    EXECUTE 'CREATE TRIGGER trg_before_update BEFORE UPDATE ON analyst.scouting_template'
         || ' FOR EACH ROW EXECUTE FUNCTION util.analyst_template_before_update()';

    -- 변경 이력 트리거 (change_log 제외 전체)
    FOREACH t IN ARRAY ARRAY['scouting_template', 'scouting_report', 'injury_note', 'tag', 'tag_assignment',
                             'custom_metric', 'custom_field', 'manual_upload', 'manual_stat', 'saved_view'] LOOP
        EXECUTE 'CREATE TRIGGER trg_audit AFTER INSERT OR UPDATE OR DELETE ON analyst.' || quote_ident(t)
             || ' FOR EACH ROW EXECUTE FUNCTION util.analyst_audit()';
    END LOOP;
END $$;

-- ---------------------------------------------------------------------
-- RLS (Row Level Security)
--  읽기: 본인 작성 또는 (workspace 공개 AND 워크스페이스 멤버)
--  쓰기: 본인 작성 행 + 분석가/관리자 역할, 관리자는 워크스페이스 공개 행 수정 가능
--  소프트 삭제(deleted_at) 필터는 API 계층에서 적용한다 (RLS 에 넣으면 소프트 삭제 UPDATE 가 막힘)
--  테이블 소유자(마이그레이션 계정)는 RLS 를 우회한다.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['scouting_report', 'injury_note', 'tag', 'custom_metric', 'custom_field',
                             'manual_upload', 'manual_stat', 'saved_view'] LOOP
        EXECUTE 'ALTER TABLE analyst.' || quote_ident(t) || ' ENABLE ROW LEVEL SECURITY';
        EXECUTE 'CREATE POLICY p_select ON analyst.' || quote_ident(t) || ' FOR SELECT USING ('
             || ' created_by = util.current_app_user()'
             || ' OR (visibility = ''workspace'''
             || '     AND util.has_workspace_role(workspace_id, ARRAY[''admin'', ''analyst'', ''viewer''])))';
        EXECUTE 'CREATE POLICY p_insert ON analyst.' || quote_ident(t) || ' FOR INSERT WITH CHECK ('
             || ' created_by = util.current_app_user()'
             || ' AND util.has_workspace_role(workspace_id, ARRAY[''admin'', ''analyst'']))';
        EXECUTE 'CREATE POLICY p_update ON analyst.' || quote_ident(t) || ' FOR UPDATE USING ('
             || ' (created_by = util.current_app_user()'
             || '  AND util.has_workspace_role(workspace_id, ARRAY[''admin'', ''analyst'']))'
             || ' OR (visibility = ''workspace'' AND util.has_workspace_role(workspace_id, ARRAY[''admin''])))';
        EXECUTE 'CREATE POLICY p_delete ON analyst.' || quote_ident(t) || ' FOR DELETE USING ('
             || ' (created_by = util.current_app_user()'
             || '  AND util.has_workspace_role(workspace_id, ARRAY[''admin'', ''analyst'']))'
             || ' OR (visibility = ''workspace'' AND util.has_workspace_role(workspace_id, ARRAY[''admin''])))';
    END LOOP;
END $$;

-- 스카우팅 템플릿: 멤버 읽기, 워크스페이스 관리자만 쓰기
