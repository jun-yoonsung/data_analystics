-- 현재 사용자가 워크스페이스에서 주어진 역할 중 하나를 갖는지 (RLS 정책에서 사용)
CREATE FUNCTION util.has_workspace_role(p_workspace_id integer, p_roles text[]) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog, pg_temp AS $$
    SELECT EXISTS (
        SELECT 1 FROM auth.workspace_member wm
        WHERE wm.workspace_id = p_workspace_id
          AND wm.user_id = util.current_app_user()
          AND wm.role = ANY (p_roles)
    )
$$;

