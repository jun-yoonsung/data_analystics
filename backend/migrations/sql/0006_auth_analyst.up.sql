    USING (util.has_workspace_role(workspace_id, ARRAY['admin', 'analyst', 'viewer']));
CREATE POLICY p_insert ON analyst.scouting_template FOR INSERT
    WITH CHECK (created_by = util.current_app_user() AND util.has_workspace_role(workspace_id, ARRAY['admin']));
-- 작성자는 트리거가 보존하므로 다른 관리자가 만든 템플릿도 수정 가능
CREATE POLICY p_update ON analyst.scouting_template FOR UPDATE
    USING (util.has_workspace_role(workspace_id, ARRAY['admin']));
CREATE POLICY p_delete ON analyst.scouting_template FOR DELETE
    USING (util.has_workspace_role(workspace_id, ARRAY['admin']));

-- 태그 부착: 보이는 태그에만, 부착 가시성은 태그 가시성을 따른다 (서브쿼리에도 tag 의 RLS 적용)
ALTER TABLE analyst.tag_assignment ENABLE ROW LEVEL SECURITY;
CREATE POLICY p_select ON analyst.tag_assignment FOR SELECT
    USING (EXISTS (SELECT 1 FROM analyst.tag t WHERE t.id = tag_id));
CREATE POLICY p_insert ON analyst.tag_assignment FOR INSERT
    WITH CHECK (created_by = util.current_app_user()
                AND util.has_workspace_role(workspace_id, ARRAY['admin', 'analyst'])
                AND EXISTS (SELECT 1 FROM analyst.tag t WHERE t.id = tag_id AND t.workspace_id = tag_assignment.workspace_id));
CREATE POLICY p_delete ON analyst.tag_assignment FOR DELETE
    USING (created_by = util.current_app_user()
           OR util.has_workspace_role(workspace_id, ARRAY['admin']));

-- 변경 이력: 본인 행위 또는 워크스페이스 관리자
ALTER TABLE analyst.change_log ENABLE ROW LEVEL SECURITY;
CREATE POLICY p_select ON analyst.change_log FOR SELECT
    USING (actor_id = util.current_app_user()
           OR util.has_workspace_role(workspace_id, ARRAY['admin']));
