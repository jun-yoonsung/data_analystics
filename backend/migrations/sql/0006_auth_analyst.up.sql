-- 모든 analyst 테이블의 AFTER 트리거: 변경 전/후 스냅숏 기록
CREATE FUNCTION util.analyst_audit() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, pg_temp AS $$
DECLARE
    old_j jsonb := CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) END;
    new_j jsonb := CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) END;
    ref   jsonb := coalesce(new_j, old_j);
BEGIN
    INSERT INTO analyst.change_log (table_name, row_id, workspace_id, op, before, after, actor_id)
    VALUES (TG_TABLE_NAME, (ref ->> 'id')::bigint, (ref ->> 'workspace_id')::integer,
            TG_OP, old_j, new_j, util.current_app_user());
    RETURN NULL;
END $$;

-- 수정 시 메타데이터 강제: 작성자·작성 시각 보존, 수정자·수정 시각·버전 갱신, 워크스페이스 이동 금지
CREATE FUNCTION util.analyst_before_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.workspace_id IS DISTINCT FROM OLD.workspace_id THEN
        RAISE EXCEPTION '워크스페이스는 변경할 수 없습니다 (table=%, id=%)', TG_TABLE_NAME, OLD.id;
    END IF;
    NEW.created_by := OLD.created_by;
    NEW.created_at := OLD.created_at;
    NEW.updated_by := util.current_app_user();
    NEW.updated_at := now();
    NEW.version    := OLD.version + 1;
    RETURN NEW;
END $$;

