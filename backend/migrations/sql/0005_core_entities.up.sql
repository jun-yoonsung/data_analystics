    ordinal        smallint NOT NULL CHECK (ordinal >= 1),
    home_score     smallint CHECK (home_score IS NULL OR home_score >= 0),
    away_score     smallint CHECK (away_score IS NULL OR away_score >= 0),
    duration_sec   integer CHECK (duration_sec IS NULL OR duration_sec >= 0),
    stats          jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(stats) = 'object'),
    source_id      integer REFERENCES ingest.data_source (id),
    ingest_run_id  bigint REFERENCES ingest.ingest_run (id) ON DELETE SET NULL,
