-- 경기
CREATE TABLE core.match (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id      integer NOT NULL,
    stage_id       integer NOT NULL,
    home_team_id   integer NOT NULL REFERENCES core.team (id),
    away_team_id   integer NOT NULL REFERENCES core.team (id),
    venue_id       integer REFERENCES core.venue (id),
    scheduled_at   timestamptz NOT NULL,
    local_date     date NOT NULL,                   -- 리그 타임존 기준 경기일 (자연키)
    game_number    smallint NOT NULL DEFAULT 1 CHECK (game_number >= 1),  -- 더블헤더 순번
    round_label    text,                            -- 라운드 (K리그 R1, V-리그 1라운드 ...)
    status         text NOT NULL DEFAULT 'scheduled'
                   CHECK (status IN ('scheduled', 'live', 'final', 'postponed', 'cancelled', 'suspended', 'forfeit')),
    home_score     smallint CHECK (home_score IS NULL OR home_score >= 0),
    away_score     smallint CHECK (away_score IS NULL OR away_score >= 0),
    winner         text CHECK (winner IN ('home', 'away', 'draw')),
    result_type    text CHECK (result_type ~ '^[A-Z][A-Z0-9_]*$'),  -- REG / OT / PSO / CALLED ...
    attendance     integer CHECK (attendance IS NULL OR attendance >= 0),
    duration_sec   integer CHECK (duration_sec IS NULL OR duration_sec >= 0),
    started_at     timestamptz,
    ended_at       timestamptz,
    attrs          jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(attrs) = 'object'),
    source_id      integer REFERENCES ingest.data_source (id),
    ingest_run_id  bigint REFERENCES ingest.ingest_run (id) ON DELETE SET NULL,
    collected_at   timestamptz,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (stage_id, season_id) REFERENCES core.competition_stage (id, season_id),
    CHECK (home_team_id <> away_team_id),
    CHECK (status <> 'final' OR (home_score IS NOT NULL AND away_score IS NOT NULL)),
    CONSTRAINT uq_match_natural UNIQUE (stage_id, home_team_id, away_team_id, local_date, game_number)
);
CREATE INDEX ix_match_scheduled ON core.match (scheduled_at);
CREATE INDEX ix_match_season_date ON core.match (season_id, local_date);
CREATE INDEX ix_match_home ON core.match (home_team_id, scheduled_at);
CREATE INDEX ix_match_away ON core.match (away_team_id, scheduled_at);

-- 경기 구간 (이닝/쿼터/세트/하프/연장). ordinal 은 경기 내 전체 순서 (Q4 다음 OT1 = 5)
