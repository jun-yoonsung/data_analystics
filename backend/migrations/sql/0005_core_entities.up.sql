-- JSONB 키 중 해당 종목 stat_definition 에 없는 코드. p_derived 는 derived 컬럼 여부.
CREATE FUNCTION util.undefined_stat_keys(p_sport_id smallint, p_stats jsonb, p_derived boolean)
RETURNS text[]
LANGUAGE sql STABLE AS $$
    SELECT coalesce(array_agg(k ORDER BY k), '{}')
    FROM jsonb_object_keys(p_stats) AS k
    WHERE NOT EXISTS (
        SELECT 1 FROM config.stat_definition sd
        WHERE sd.sport_id = p_sport_id AND sd.code = k AND sd.is_derived = p_derived
    )
$$;

CREATE VIEW core.v_stat_key_violations AS
WITH rows AS (
    SELECT 'player_match_stat' AS table_name, x.id AS row_id, m.season_id, x.stats, x.derived
    FROM core.player_match_stat x JOIN core.match m ON m.id = x.match_id
    UNION ALL
    SELECT 'team_match_stat', x.id, m.season_id, x.stats, x.derived
    FROM core.team_match_stat x JOIN core.match m ON m.id = x.match_id
    UNION ALL
    SELECT 'player_season_stat', x.id, x.season_id, x.stats, x.derived FROM core.player_season_stat x
    UNION ALL
    SELECT 'team_season_stat', x.id, x.season_id, x.stats, x.derived FROM core.team_season_stat x
    UNION ALL
    SELECT 'standing', x.id, cs.season_id, x.stats, '{}'::jsonb
    FROM core.standing x JOIN core.competition_stage cs ON cs.id = x.stage_id
), checked AS (
    SELECT r.table_name, r.row_id, c.sport_code,
           util.undefined_stat_keys(c.sport_id, r.stats, false) AS undefined_raw_keys,
           util.undefined_stat_keys(c.sport_id, r.derived, true) AS undefined_derived_keys
    FROM rows r JOIN core.v_season_context c ON c.season_id = r.season_id
)
SELECT * FROM checked
WHERE undefined_raw_keys <> '{}' OR undefined_derived_keys <> '{}';

-- external_id_map 에서 가리키는 엔티티가 사라진 매핑
CREATE VIEW core.v_external_id_orphans AS
SELECT m.*
FROM ingest.external_id_map m
WHERE NOT CASE m.entity_type
    WHEN 'league' THEN EXISTS (SELECT 1 FROM core.league x WHERE x.id = m.entity_id)
    WHEN 'season' THEN EXISTS (SELECT 1 FROM core.season x WHERE x.id = m.entity_id)
    WHEN 'stage'  THEN EXISTS (SELECT 1 FROM core.competition_stage x WHERE x.id = m.entity_id)
    WHEN 'team'   THEN EXISTS (SELECT 1 FROM core.team x WHERE x.id = m.entity_id)
    WHEN 'player' THEN EXISTS (SELECT 1 FROM core.player x WHERE x.id = m.entity_id)
    WHEN 'venue'  THEN EXISTS (SELECT 1 FROM core.venue x WHERE x.id = m.entity_id)
    WHEN 'match'  THEN EXISTS (SELECT 1 FROM core.match x WHERE x.id = m.entity_id)
    ELSE false
END;
