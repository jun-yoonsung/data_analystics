-- 연도 파티션 생성 헬퍼 (수집 워커가 새 시즌 시작 전에 호출)
CREATE FUNCTION util.ensure_event_partition(p_year integer) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    part_name text := 'event_y' || p_year::text;
BEGIN
    IF to_regclass('core.' || part_name) IS NULL THEN
        EXECUTE 'CREATE TABLE core.' || quote_ident(part_name)
             || ' PARTITION OF core.event FOR VALUES FROM ('
             || quote_literal(make_date(p_year, 1, 1)) || ') TO ('
             || quote_literal(make_date(p_year + 1, 1, 1)) || ')';
    END IF;
END $$;

CREATE TABLE core.event_default PARTITION OF core.event DEFAULT;
SELECT util.ensure_event_partition(y) FROM generate_series(2023, 2027) AS y;

